/** Ссылка на источник: ID в справочнике источников и короткое название для экрана. */
export type LogicSource = readonly [SourceId, string];

export interface LogicItem {
  text: string;
  /** Пояснение мелким шрифтом. */
  note?: string;
  sources?: readonly LogicSource[];
  /** Пока вручную, хотя должно находиться само, — выделяется на карте. */
  gap?: boolean;
}

export interface LogicStep {
  n: number;
  title: string;
  /** Вопрос, на который отвечает шаг. */
  question: string;
  /** Шаг проекта, где это видно (`sec` в адресе проекта). */
  sec: string;
  lanes: Record<LogicLane, readonly LogicItem[]>;
}

