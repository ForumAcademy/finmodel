/** Ссылка источника для экрана: короткое название, адрес (у документов проекта — нет) и сверено ли содержание. */
export interface LogicLink {
  id: SourceId;
  label: string;
  url: string | null;
  /** false — ссылка есть, но содержание ещё не сверено с формулировкой в справочнике. */
  verified: boolean;
}

export const logicLinks = (item: LogicItem): LogicLink[] =>
  (item.sources ?? []).map(([id, label]) => {
    const s = getSource(id);
    return { id, label, url: s.url ?? null, verified: s.verified !== false };
  });
